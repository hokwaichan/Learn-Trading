/** Legs for the payoff widget. direction: 1 = bought, -1 = sold. */
const call = (direction: 1 | -1, strike: number, premium: number) => ({ kind: 'option', type: 'call', direction, quantity: 1, strike, entryPrice: premium });
const put = (direction: 1 | -1, strike: number, premium: number) => ({ kind: 'option', type: 'put', direction, quantity: 1, strike, entryPrice: premium });
const stock = (direction: 1 | -1, price: number) => ({ kind: 'stock', direction, quantity: 1, entryPrice: price });
const payoff = (title: string, legs: unknown[], spot = 100) => widget('payoff', { title, legs, spot });

